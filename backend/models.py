from typing import List, Optional, Dict, Any, Union
from pydantic import BaseModel, Field, field_validator

class ClaimItem(BaseModel):
    text: str = Field(default="", description="The selected text passage")
    title: Optional[str] = Field(default="Untitled Source", description="Webpage or document title")
    url: Optional[str] = Field(default="", description="Source URL")

    @field_validator("title", mode="before")
    def default_title_if_none(cls, v: Optional[str]) -> str:
        if v is None or not str(v).strip():
            return "Untitled Source"
        return str(v).strip()

    @field_validator("url", mode="before")
    def default_url_if_none(cls, v: Optional[str]) -> str:
        if v is None:
            return ""
        return str(v).strip()


class SourceItem(BaseModel):
    title: str = Field(default="Untitled Source", description="Source title")
    url: str = Field(..., description="Actual URL of the source")
    snippet: str = Field(default="", description="Search snippet or excerpt from page")
    content_type: str = Field(default="snippet", description="Distinguishes 'snippet' from 'full_page'")
    is_relevant: bool = Field(default=True, description="Whether this source contains evidence for the claim")
    relevance_score: float = Field(default=0.0, ge=0.0, le=1.0, description="Relevance score between 0 and 1")
    verified_claim: Optional[str] = Field(default=None, description="What specific fact was verified by this source")


class CompareRequest(BaseModel):
    claim_a: ClaimItem
    claim_b: Optional[ClaimItem] = Field(default=None, description="Secondary passage or evidence")
    include_search: bool = Field(default=False, description="Whether to discover additional web sources")
    max_search_results: int = Field(default=3, ge=1, le=10, description="Max search sources to retrieve")


class CompareResponse(BaseModel):
    classification: str = Field(
        ...,
        description="One of: SUPPORTED, CONTRADICTED, PARTIALLY_SUPPORTED, DIFFERENT_CONTEXT, INSUFFICIENT_EVIDENCE, UNRELATED (or legacy: possible_contradiction, consistent, different_context, insufficient_context)"
    )
    explanation: str = Field(..., description="Short, objective explanation of relationship between statements")
    
    # Passages interpretation
    interpretation_a: Optional[str] = Field(default="", description="Interpretation of passage A")
    interpretation_b: Optional[str] = Field(default="", description="Interpretation of passage B")
    
    # Evidence breakdown
    supporting_evidence: List[str] = Field(default_factory=list, description="Specific supporting evidence quotes or facts")
    contradicting_evidence: List[str] = Field(default_factory=list, description="Specific contradicting evidence quotes or facts")
    evidence_a: str = Field(default="", description="Primary evidence excerpt from passage A")
    evidence_b: str = Field(default="", description="Primary evidence excerpt from passage B")
    
    # Context analysis
    key_differences: List[str] = Field(default_factory=list, description="Important factual differences")
    missing_context: List[str] = Field(default_factory=list, description="Contextual elements missing or needed")
    verification_questions: List[str] = Field(default_factory=list, description="Questions user should investigate")
    
    # Confidence and justification
    confidence: float = Field(default=0.8, ge=0.0, le=1.0, description="Confidence score from 0.0 to 1.0")
    confidence_justification: str = Field(default="", description="Reasoning for assigned confidence level")
    
    # Source attribution and grounding
    source_attribution: Optional[str] = Field(default=None, description="Attribution note or primary authority")
    additional_sources: List[SourceItem] = Field(default_factory=list, description="Retrieved external sources with real URLs")
    
    # Limitations and fallback indicator
    limitations: List[str] = Field(default_factory=list, description="Explicit boundaries and limitations of this analysis")
    is_heuristic_fallback: bool = Field(default=False, description="True if generated by deterministic heuristic fallback, not live AI")

    @field_validator(
        "key_differences", "missing_context", "verification_questions",
        "supporting_evidence", "contradicting_evidence", "limitations",
        "additional_sources",
        mode="before"
    )
    def ensure_list_not_none(cls, v: Any) -> list:
        if v is None:
            return []
        if isinstance(v, list):
            return v
        return [str(v)]

    @field_validator("evidence_a", "evidence_b", "explanation", mode="before")
    def ensure_str_not_none(cls, v: Any) -> str:
        if v is None:
            return ""
        return str(v)
